CREATE TABLE authorizations (
 id VARCHAR(36) PRIMARY KEY,
 beneficiary VARCHAR(80) NOT NULL,
 agreement VARCHAR(80) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(beneficiary, agreement)
);
CREATE TABLE operations (
 id VARCHAR(36) PRIMARY KEY,
 idempotency_key VARCHAR(100) NOT NULL UNIQUE,
 payload_hash VARCHAR(64) NOT NULL,
 payload TEXT NOT NULL,
 beneficiary VARCHAR(80) NOT NULL,
 status VARCHAR(32) NOT NULL,
 protocol VARCHAR(36),
 attempts INTEGER NOT NULL DEFAULT 0,
 next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
 last_error VARCHAR(1000),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CHECK(status IN ('RECEBIDA','PENDENTE','CONFIRMADA','REJEITADA','REVISAO_NECESSARIA'))
);
CREATE INDEX operations_due_idx ON operations(status, next_attempt_at);
CREATE TABLE reservations (
 beneficiary VARCHAR(80) NOT NULL,
 installment_id VARCHAR(80) NOT NULL,
 operation_id VARCHAR(36) NOT NULL REFERENCES operations(id),
 PRIMARY KEY(beneficiary, installment_id)
);
CREATE TABLE receiving_accounts (
 beneficiary VARCHAR(80) NOT NULL,
 installment_id VARCHAR(80) NOT NULL,
 account_json TEXT NOT NULL,
 operation_id VARCHAR(36) NOT NULL REFERENCES operations(id),
 PRIMARY KEY(beneficiary, installment_id)
);
CREATE TABLE audit_events (
 sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 operation_id VARCHAR(36) NOT NULL REFERENCES operations(id),
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
 type VARCHAR(64) NOT NULL,
 detail VARCHAR(2000) NOT NULL
);
CREATE INDEX events_operation_idx ON audit_events(operation_id, sequence);
CREATE TABLE central_installments (
 id VARCHAR(80) PRIMARY KEY,
 beneficiary VARCHAR(80) NOT NULL,
 agreement VARCHAR(80) NOT NULL,
 amount NUMERIC(14,2) NOT NULL,
 due_date DATE NOT NULL,
 status VARCHAR(20) NOT NULL,
 account_json TEXT
);
CREATE TABLE central_operations (
 protocol VARCHAR(36) PRIMARY KEY,
 idempotency_key VARCHAR(100) UNIQUE NOT NULL,
 payload_hash VARCHAR(64) NOT NULL,
 payload TEXT NOT NULL,
 beneficiary VARCHAR(80) NOT NULL,
 scenario VARCHAR(40) NOT NULL,
 status VARCHAR(20) NOT NULL,
 reason VARCHAR(200),
 confirm_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE central_reservations (
 installment_id VARCHAR(80) PRIMARY KEY REFERENCES central_installments(id),
 protocol VARCHAR(36) NOT NULL REFERENCES central_operations(protocol)
);
CREATE TABLE simulation_attempts (
 idempotency_key VARCHAR(100) PRIMARY KEY,
 attempts INTEGER NOT NULL
);
